#!/usr/bin/env python3
"""Self-host the Arabic UI fonts so they work under the strict CSP.

Google Fonts is used only at build time to obtain the licensed woff2 files.
The generated CSS and font files are committed to both static folders, so the
running app makes no third-party requests and needs no CSP relaxation.

Usage: python scripts/fetch_fonts.py
"""

from __future__ import annotations

import pathlib
import re
import shutil
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
CSS_URL = (
    "https://fonts.googleapis.com/css2?"
    "family=Tajawal:wght@400;500;700;800;900&display=swap"
)
UA = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/120.0 Safari/537.36"
)
FONTS = ROOT / "06-STOREFRONT/themes/default/static/fonts"
TARGETS = [
    ROOT / "06-STOREFRONT/themes/default/static",
    ROOT / "07-ADMIN/static",
]


def download(url: str, dest: pathlib.Path) -> None:
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=45) as resp:
        data = resp.read()
    if len(data) < 2000:
        raise RuntimeError(f"suspicious font size: {len(data)}")
    dest.write_bytes(data)


def main() -> None:
    FONTS.mkdir(parents=True, exist_ok=True)
    for stale in FONTS.glob("*.woff2"):
        stale.unlink()
    req = urllib.request.Request(CSS_URL, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=45) as resp:
        css = resp.read().decode("utf-8")

    pattern = re.compile(
        r"/\*\s*([\w-]+)\s*\*/\s*@font-face\s*\{([^}]*)\}", re.MULTILINE
    )
    out: list[str] = [
        "/* Self-hosted Arabic/Latin fonts. Generated by scripts/fetch_fonts.py. */",
        "",
    ]
    count = 0
    for subset, body in pattern.findall(css):
        if subset not in ("arabic", "latin"):
            continue
        family = re.search(r"font-family:\s*'([^']+)'", body).group(1)
        weight = re.search(r"font-weight:\s*([^;]+);", body).group(1).strip()
        url = re.search(r"url\((https://[^)]+)\)", body).group(1)
        unicode_range = re.search(r"unicode-range:\s*([^;]+);", body).group(1).strip()
        slug = family.lower().replace(" ", "-") + "-" + weight.replace(" ", "-")
        name = f"{slug}-{subset}.woff2"
        download(url, FONTS / name)
        out.append(
            "@font-face {\n"
            f"  font-family: '{family}';\n"
            "  font-style: normal;\n"
            f"  font-weight: {weight};\n"
            "  font-display: swap;\n"
            f"  src: url('/store/static/fonts/{name}') format('woff2');\n"
            f"  unicode-range: {unicode_range};\n"
            "}\n"
        )
        count += 1

    generated = "\n".join(out).rstrip() + "\n"
    # The admin app serves its assets under /admin/static/, so emit two CSS
    # variants with the correct URL prefix.
    for target in TARGETS:
        prefix = "/admin/static/" if "07-ADMIN" in str(target) else "/store/static/"
        (target / "css/fonts.css").write_text(
            generated.replace("/store/static/fonts/", prefix + "fonts/"),
            encoding="utf-8",
        )
        dst = target / "fonts"
        if dst.resolve() == FONTS.resolve():
            continue
        if dst.exists():
            shutil.rmtree(dst)
        shutil.copytree(FONTS, dst)
    print(f"self-hosted {count} font files")


if __name__ == "__main__":
    main()
